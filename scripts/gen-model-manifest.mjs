// Scans /public/models for model files and writes data/modelManifest.ts — the
// list of slugs the app should auto-resolve to 3D models. This is what makes
// "drop a .glb in and it shows up on unlock" work with no code edits.
//
// Runs automatically before `dev`/`build` (see package.json), or on demand:
//   npm run models:manifest
//
// Name each file by the slug of the entity, e.g. king-black-dragon.glb.
// `placeholder.glb` (our own test cube) is ignored.
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';

const DIR = 'public/models';
const OUT = 'data/modelManifest.ts';

let slugs = [];
try {
  mkdirSync(DIR, { recursive: true });
  slugs = readdirSync(DIR)
    .filter((f) => /\.(glb|gltf)$/i.test(f))
    .map((f) => f.replace(/\.(glb|gltf)$/i, ''))
    .filter((s) => s !== 'placeholder')
    .sort();
} catch (e) {
  console.warn('[models] could not scan', DIR, '-', e?.message ?? e);
}

const body = slugs.map((s) => `  ${JSON.stringify(s)},`).join('\n');
writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-model-manifest.mjs — do not edit by hand.\n` +
  `// Slugs of the 3D models present in /public/models (run \`npm run models:manifest\`).\n` +
  `export const MODEL_SLUGS: string[] = [\n${body}${body ? '\n' : ''}];\n`,
);
console.log(`[models] wrote ${OUT} with ${slugs.length} model(s)`);
