// Scans /public/models for model files and writes data/modelManifest.ts — a
// slug → filename map the app uses to auto-resolve a 3D model for an unlock.
// This is what makes "drop a model in and it shows up on unlock" work with no
// code edits.
//
// Runs automatically before `dev`/`build` (see package.json), or on demand:
//   npm run models:manifest
//
// Name each file by the slug of the entity, e.g. king-black-dragon.glb (or
// .gltf). `placeholder.glb` (our own test cube) is ignored.
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';

const DIR = 'public/models';
const OUT = 'data/modelManifest.ts';

let files = [];
try {
  mkdirSync(DIR, { recursive: true });
  files = readdirSync(DIR)
    .filter((f) => /\.(glb|gltf)$/i.test(f))
    .filter((f) => f.replace(/\.(glb|gltf)$/i, '') !== 'placeholder')
    .sort();
} catch (e) {
  console.warn('[models] could not scan', DIR, '-', e?.message ?? e);
}

const entries = files.map((f) => {
  const slug = f.replace(/\.(glb|gltf)$/i, '');
  return `  ${JSON.stringify(slug)}: ${JSON.stringify(f)},`;
}).join('\n');

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-model-manifest.mjs — do not edit by hand.\n` +
  `// Maps an entity slug to its model file in /public/models (run \`npm run models:manifest\`).\n` +
  `export const MODEL_FILES: Record<string, string> = {\n${entries}${entries ? '\n' : ''}};\n`,
);
console.log(`[models] wrote ${OUT} with ${files.length} model(s)`);
