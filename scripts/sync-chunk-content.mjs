#!/usr/bin/env node
/** Regenerate Chunk Picker runtime data only from the reviewed local source pin. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPinnedChunkSource } from './chunk-source.mjs';
import { assertChunkTransform, transformChunkContent } from './chunk-content-transform.mjs';
import { collectNamedTaskUnlockSourceInventory, readNamedTaskUnlockRegistry, validateNamedTaskUnlockRegistry } from './named-task-unlock-locations.mjs';
import { readBankLocationRegistry, validateBankLocationRegistry } from './bank-locations.mjs';
import { generatedTextMatches } from './generated-text.mjs';
import { validateInteriorAccessPolicy } from './chunk-interiors.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function chunkNamesSource(result) {
  const names = Object.fromEntries(Object.entries(result.full.chunks)
    .filter(([, entry]) => entry.n)
    .sort(([left], [right]) => Number(left) - Number(right))
    .map(([id, entry]) => {
      const regionId = Number(id);
      return [`${regionId >> 8},${regionId & 255}`, entry.n];
    }));
  return `// AUTO-GENERATED by scripts/sync-chunk-content.mjs — do not edit by hand.\n// Source-backed Chunk Picker place names from the reviewed local source pin.\n// Keyed "cx,cy"; unnamed chunks are deliberately absent.\n\nexport const CHUNK_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};\n`;
}

const OUTPUTS = [
  [resolve(ROOT, 'public', 'chunk-content.json'), (result) => JSON.stringify(result.full)],
  [resolve(ROOT, 'data', 'chunkContentLite.ts'), (result) => result.liteSource],
  [resolve(ROOT, 'data', 'chunkNames.ts'), chunkNamesSource],
  [resolve(ROOT, 'data', 'sources', 'chunk-content-transform-audit.json'), (result) => `${JSON.stringify(result.audit, null, 2)}\n`],
];

function expectedFiles(result) {
  return OUTPUTS.map(([path, serialize]) => [path, serialize(result)]);
}

function check(expected) {
  const stale = expected
    .filter(([path, text]) => !existsSync(path)
      || !generatedTextMatches(readFileSync(path, 'utf8'), text))
    .map(([path]) => path);
  if (stale.length) throw new Error(`Chunk content outputs are stale:\n${stale.map((path) => `  ${path}`).join('\n')}`);
}

const args = process.argv.slice(2);
if (args.some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/sync-chunk-content.mjs [--check]');
const checkOnly = args.includes('--check');
const { manifest, data } = await readPinnedChunkSource();
validateInteriorAccessPolicy(data);
const namedLocationRegistry = readNamedTaskUnlockRegistry();
const inventory = collectNamedTaskUnlockSourceInventory(data);
validateNamedTaskUnlockRegistry(namedLocationRegistry, {
  sourceCommit: manifest.commit,
  sourceLocationKeys: inventory.locationKeys,
  validChunkIds: new Set((data.walkableChunks ?? []).map(String)),
});
const bankLocationRegistry = readBankLocationRegistry();
validateBankLocationRegistry(bankLocationRegistry, {
  validChunkIds: new Set((data.walkableChunks ?? []).map(String)),
  validBankIds: new Set((data.rollingChunks?.bank ?? []).map((raw) => String(raw).split('-')[0])),
});
const result = transformChunkContent(data, manifest, namedLocationRegistry, bankLocationRegistry);
assertChunkTransform(result, manifest);
const expected = expectedFiles(result);

if (checkOnly) {
  check(expected);
  console.log(`Chunk content outputs match reviewed source ${manifest.commit}.`);
} else {
  for (const [path, bytes] of expected) writeFileSync(path, bytes);
  console.log(`Wrote chunk content outputs from reviewed source ${manifest.commit}: ${Object.keys(result.full.chunks).length} chunks with content.`);
}
