/** The Banks roll pool order: data/sources/bank-roll-order.json's ids. */
export function readBankRollOrder(path = ROLL_ORDER_PATH) {
  return JSON.parse(readFileSync(path, 'utf8')).ids;
}

/**
 * Puts the banks in the roll pool's fixed order. Seeded runs replay their draws by
 * position in BANK_IDS, so the order never follows the labels: a renamed bank keeps
 * its place. Every bank needs a place, and a new bank goes at the end of the list.
 */
export function orderBanksForRolls(defs, rollOrder = readBankRollOrder()) {
  const position = new Map(rollOrder.map((id, index) => [String(id), index]));
  if (position.size !== rollOrder.length) throw new Error('data/sources/bank-roll-order.json lists a bank twice');
  const ids = new Set(defs.map(({ id }) => id));
  const unknown = rollOrder.filter(id => !ids.has(String(id)));
  if (unknown.length) throw new Error(`data/sources/bank-roll-order.json lists ids that are not banks: ${unknown.join(', ')}`);
  const missing = defs.filter(({ id }) => !position.has(id)).map(({ id }) => id);
  if (missing.length) {
    throw new Error(`Banks with no place in data/sources/bank-roll-order.json (add them at the end): ${missing.join(', ')}`);
  }
  return [...defs].sort((a, b) => position.get(a.id) - position.get(b.id));
}

export function buildBankDefinitions(doc, registry, rollOrder = readBankRollOrder()) {
  const chunks = doc.chunks ?? {};
  const labels = bankLocationLabels(registry);
  const merged = new Set(bankMerges(registry).map(({ id }) => id));
  const bankIds = [...new Set((doc.banks ?? []).map(String))].filter(id => !merged.has(id));
  const physicalDefs = bankIds
    .map(id => ({ id, name: (labels.get(id) ?? chunks[id]?.n ?? chunks[id]?.name ?? `Bank ${id}`).trim() }));
  const virtualDefs = bankVirtualLocations(registry)
    .map(({ id, name }) => ({ id, name: name.trim() }));
  const defs = orderBanksForRolls([...physicalDefs, ...virtualDefs], rollOrder);
  const areas = bankAreas(registry);
  for (const def of defs) if (areas.has(def.id)) def.area = areas.get(def.id);

  const seen = new Set();
  for (const def of defs) {
    if (seen.has(def.name)) def.name = `${def.name} (${def.id})`;
    seen.add(def.name);
  }
  return defs;
}

export function generateBankSource(doc, registry) {
  const defs = buildBankDefinitions(doc, registry);
  const merges = bankMerges(registry);
  const physicalCount = new Set((doc.banks ?? []).map(String)).size - merges.length;
  const virtualCount = bankVirtualLocations(registry).length;
  const virtualEntryLabel = virtualCount === 1 ? 'entry' : 'entries';
  const body = defs.map(def => `  { id: '${def.id}', name: ${JSON.stringify(def.name)}${def.area ? `, area: ${JSON.stringify(def.area)}` : ''} },`).join('\n');
  const mergeBody = merges.map(({ id, into }) => `  '${id}': '${into}',`).join('\n');
  return `// AUTO-GENERATED by scripts/gen-banks.mjs — do not edit by hand.
// The ${defs.length} bankable unlocks: ${physicalCount} physical chunk entries plus
// ${virtualCount} virtual registry ${virtualEntryLabel}. Each is its own unlock in bank-locked modes.
// Physical entries are keyed by canonical chunk id "cx*256+cy".

/** area: the area the bank stands in, where its chunk is only the entrance to a place filed under another. */
export interface BankDef { id: string; name: string; area?: string }

export const BANKS: BankDef[] = [
${body}
];

/** All bank ids, for the roll pool, in the fixed order of data/sources/bank-roll-order.json. */
export const BANK_IDS: string[] = BANKS.map((b) => b.id);

/** id → definition, for label lookups. */
export const BANK_BY_ID: Record<string, BankDef> =
  Object.fromEntries(BANKS.map((b) => [b.id, b]));

/** Canonical chunk id for a chunk coordinate — the bank's unlock key. */
export const bankId = (cx: number, cy: number): string => String(cx * 256 + cy);

/**
 * Bank unlocks that open no bank, and the bank each leads to. A save that
 * owns one owns that bank instead (data/sources/bank-locations.json merges).
 */
export const MERGED_BANKS: Readonly<Record<string, string>> = {
${mergeBody}
};
`;
}

/**
 * What a bank facility looks like, by its name: an object or NPC in the chunk data, or a facility
 * the registry names ("Keldagrim bank"). None for a service such as an animal.
 */
export function facilityPictureKind(name, kind = 'object') {
  const n = name.trim().toLowerCase();
  if (kind === 'npc') return /banker$/.test(n) ? 'booth' : undefined;
  if (/^(bank booth|private bank booth|bank table|bank counter)$/.test(n) || (kind === 'registry' && / banks?$/.test(n))) return 'booth';
  if (/^(bank deposit box|deposit box|deposit pool)$/.test(n) || /deposit (box|boxes|pool)$/.test(n)) return 'box';
  if (/^bank (deposit )?chest/.test(n) || /(bank|deposit) chests?$/.test(n)) return 'chest';
  return undefined;
}

const PICTURE_RANK = ['booth', 'chest', 'box'];

/**
 * Every bank facility of each physical bank's place: its chunk, the interiors entered from it, the
 * chunks merged into it (as the chunk data names their objects and NPCs), then the registry's
 * facilities and reviewed facilities, which are marked reviewed.
 */
function eachBankFacility(doc, registry, defs, visit) {
  const addContent = (id, content) => {
    for (const [name] of content?.o ?? []) visit(id, name, 'object', false);
    for (const name of content?.p ?? []) visit(id, name, 'npc', false);
  };
  for (const { id } of defs) addContent(id, doc.chunks?.[id]);
  for (const { into, id } of bankMerges(registry)) addContent(into, doc.chunks?.[id]);
  for (const interior of Object.values(doc.interiors ?? {})) {
    for (const entrance of interior.entrances ?? []) addContent(String(entrance.chunkId), interior.content);
  }
  for (const location of registry.locations) for (const name of location.facilities ?? []) visit(location.id, name, 'registry', true);
  for (const facility of registry.reviewedFacilities ?? []) visit(facility.id, facility.name, facility.kind, true);
}

/**
 * NPCs who take items into the bank but never open it, by the name the registry gives them,
 * checked on the Wiki in November 2026. Their names say nothing of it.
 */
export const DEPOSIT_SERVICES = {
  // 'Peer the Seer' revision 15403084: options Talk-to, Deposit-items; after the easy Fremennik
  // Diary he "acts as a bank deposit box".
  'Peer the Seer': 'deposit',
  // 'Rionasta' revision 15310502: options Talk-to, Send-parcel; ships inventory items to the bank
  // for trading sticks.
  Rionasta: 'deposit',
};

/**
 * Whether a facility opens the bank ('bank') or only takes deposits ('deposit'), by its name:
 * a deposit box, pool or chest, or a reviewed deposit service, only takes deposits; a booth, a
 * banker or a bank chest opens the bank. Undefined for anything else.
 */
export function facilityBankUse(name, kind = 'object') {
  if (DEPOSIT_SERVICES[name.trim()] && (kind === 'npc' || kind === 'registry')) return 'deposit';
  const picture = facilityPictureKind(name, kind);
  if (!picture) return undefined;
  if (picture === 'box' || /deposit/i.test(name)) return 'deposit';
  return 'bank';
}

/**
 * The physical banks whose place only takes deposits: a reviewed facility there takes deposits
 * (a registry facility or reviewed facility; a deposit box in the chunk data alone decides nothing,
 * as for the pictures) and nothing there, in the chunk data or the registry, opens the bank.
 * Decided from the facilities, never from the place's name.
 */
export function buildDepositOnlyBanks(doc, registry, defs = buildBankDefinitions(doc, registry)) {
  const deposit = new Set();
  const opens = new Set();
  eachBankFacility(doc, registry, defs, (id, name, kind, reviewed) => {
    const use = facilityBankUse(name, kind);
    if (use === 'bank') opens.add(id);
    if (use === 'deposit' && reviewed) deposit.add(id);
  });
  return defs.map(({ id }) => id).filter((id) => /^\d+$/.test(id) && deposit.has(id) && !opens.has(id))
    .sort((a, b) => Number(a) - Number(b));
}

export function generateBankDepositOnlySource(doc, registry) {
  const ids = buildDepositOnlyBanks(doc, registry);
  return `// AUTO-GENERATED by scripts/gen-banks.mjs — do not edit by hand.
// The banks whose place only takes deposits (a deposit box, a deposit chest or an NPC who sends
// items to the bank), from the facilities at each place. Only utils/bankDecisions.ts reads it, for
// the RuneLite export, so it stays out of data/banks.ts, which loads with the app's first screen.

export const DEPOSIT_ONLY_BANK_IDS: readonly string[] = [${ids.map((id) => `'${id}'`).join(', ')}];
`;
}

/**
 * Each physical bank's picture: a booth where the place has a booth or a banker, else a chest,
 * else a deposit box. It reads the place's chunk, the interiors entered from it, the chunks merged
 * into it and the registry's facilities. A bank with none found is left out (the label decides).
 * A deposit box in the chunk data alone decides nothing: several full banks have a teller with a
 * name of their own (Jatizso's Magnus Gram, Corsair Cove's Yusuf) that the data does not mark.
 */
export function buildBankPictureKinds(doc, registry, defs = buildBankDefinitions(doc, registry)) {
  const facilities = new Map();
  eachBankFacility(doc, registry, defs, (id, name, kind, reviewed) => {
    const picture = facilityPictureKind(name, kind);
    if (!picture || (picture === 'box' && !reviewed)) return;
    if (!facilities.has(id)) facilities.set(id, new Set());
    facilities.get(id).add(picture);
  });
  return Object.fromEntries(defs.filter(({ id }) => /^\d+$/.test(id) && facilities.has(id))
    .map(({ id }) => [id, PICTURE_RANK.find(kind => facilities.get(id).has(kind))]));
}

export function generateBankPictureSource(doc, registry) {
  const kinds = buildBankPictureKinds(doc, registry);
  const body = Object.entries(kinds).map(([id, kind]) => `  '${id}': '${kind}',`).join('\n');
  return `// AUTO-GENERATED by scripts/gen-banks.mjs — do not edit by hand.
// Each bank's picture in the OSRS layout, from the facilities at its place: its chunk, the
// interiors entered from it and the registry. Only utils/bankPicture.ts reads it, so it stays out
// of data/banks.ts, which loads with the app's first screen. A bank not listed is drawn by its label.

export type BankPictureKind = 'booth' | 'chest' | 'box';

export const BANK_PICTURE_KINDS: Readonly<Record<string, BankPictureKind>> = {
${body}
};
`;
}

/**
 * The registry's access rules without its evidence (wiki links, notes), which only its own checks need.
 * Written to a file of its own: data/banks.ts loads with the app's first screen, and only
 * utils/entityAccess.ts, which loads on demand, reads these rules.
 */
export function generateBankAccessSource(registry) {
  const merges = bankMerges(registry);
  const rows = (entries) => entries.map(entry => `  ${JSON.stringify(entry)},`).join('\n');
  const facilityBody = rows(registry.reviewedFacilities.map(({ id, name, kind, requirements }) =>
    ({ id, name, kind, ...(requirements?.length ? { requirements } : {}) })));
  // A merged location is no bank of its own, so the app has no rules for it.
  const mergedIds = new Set(merges.map(({ id }) => id));
  const locationBody = rows(registry.locations.filter(({ id }) => !mergedIds.has(id))
    .map(({ id, accessOptions }) => ({ id, ...(accessOptions ? { accessOptions } : {}) })));
  const gateBody = rows((registry.accessGates ?? []).map(({ id, accessOptions }) => ({ id, accessOptions })));
  return `// AUTO-GENERATED by scripts/gen-banks.mjs — do not edit by hand.
// How each bank is entered, from data/sources/bank-locations.json. Kept out of data/banks.ts so
// these rules load on demand with utils/entityAccess.ts, not with the app's first screen.

/** One way into a bank: quests, diaries, guilds (the unlock and its entry) or checks to confirm. */
export interface BankAccessOption { quests?: string[]; diaries?: string[]; guilds?: string[]; skills?: string[]; manual?: string[] }

/** Bank facilities the registry reviewed, such as the bank buffalo, with what each needs. */
export const BANK_REVIEWED_FACILITIES: readonly { id: string; name: string; kind: string; requirements?: string[] }[] = [
${facilityBody}
];

/** The registry's reviewed locations (their names are their BANKS labels), with a service's own ways in. */
export const BANK_REVIEWED_LOCATIONS: readonly { id: string; accessOptions?: BankAccessOption[] }[] = [
${locationBody}
];

/** The ways into a whole bank that every facility in it needs: its guild, or its town's quest. */
export const BANK_ACCESS_GATES: readonly { id: string; accessOptions: BankAccessOption[] }[] = [
${gateBody}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/gen-banks.mjs [--check]');
  const doc = JSON.parse(readFileSync(DOC_PATH, 'utf8'));
  const registry = readBankLocationRegistry();
  validateBankLocationRegistry(registry, {
    validChunkIds: new Set(Object.keys(doc.chunks ?? {})),
    validBankIds: new Set((doc.banks ?? []).map(String)),
  });
  const outputs = [
    [OUTPUT_PATH, 'data/banks.ts', generateBankSource(doc, registry)],
    [ACCESS_OUTPUT_PATH, 'data/bankAccess.ts', generateBankAccessSource(registry)],
    [PICTURE_OUTPUT_PATH, 'data/bankPictureKinds.ts', generateBankPictureSource(doc, registry)],
    [DEPOSIT_ONLY_OUTPUT_PATH, 'data/bankDepositOnly.ts', generateBankDepositOnlySource(doc, registry)],
  ];
  if (args.includes('--check')) {
    for (const [path, label, expected] of outputs) {
      if (!existsSync(path) || !generatedTextMatches(readFileSync(path, 'utf8'), expected)) {
        throw new Error(`Generated bank definitions are stale: ${label}`);
      }
    }
    console.log('Generated bank definitions are current.');
  } else {
    for (const [path, , expected] of outputs) writeFileSync(path, expected);
    console.log(`Wrote data/banks.ts with ${buildBankDefinitions(doc, registry).length} banks.`);
  }
}
